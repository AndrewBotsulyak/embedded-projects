#ifndef LX200_FORMAT_H
#define LX200_FORMAT_H

#include <cstddef>
#include <cstdint>

// ============================================================================
//  ФОРМАТЫ ПРОТОКОЛА LX200 — общее для монтировки и пульта
// ============================================================================
//
//  Только перевод «строка ↔ число», без команд и без моторов (info/lx200.md, раздел 4).
//  Внутри прошивки координаты хранятся целыми числами:
//    RA  — секунды времени:   0 … 86 399           (05:35:17  → 20 117)
//    DEC — угловые секунды:   −324 000 … +324 000  (+22*00:52 → 79 252)
//
//  Строки передаются БЕЗ ':' команды и без '#': парсер команд убирает их сам.
// ============================================================================

#define LX200_RA_MAX_SEC      86400    // 24 ч в секундах (RA 86 400 = снова 0)
#define LX200_DEC_MAX_ARCSEC  324000   // 90° в угловых секундах

// Направление ручного движения: буква в командах :Mn# :Qe# ...
enum lx200_dir_t {
    LX200_DIR_N,   // 'n' — север (ось DEC)
    LX200_DIR_S,   // 's' — юг    (ось DEC)
    LX200_DIR_E,   // 'e' — восток (ось RA)
    LX200_DIR_W,   // 'w' — запад  (ось RA)
};

// Скорость ручного движения: буква в командах :RG# :RC# :RM# :RS#
enum lx200_rate_t {
    LX200_RATE_GUIDE,    // 'G' — правка, гидирование
    LX200_RATE_CENTER,   // 'C' — центрирование
    LX200_RATE_FIND,     // 'M' — поиск
    LX200_RATE_SLEW,     // 'S' — перекладка
};

/*
    Разобрать RA. Понимает:
      "HH:MM:SS"  — длинный формат       ("05:35:17")
      "HH:MM.T"   — короткий, T — десятые доли минуты ("05:35.3")
      "HH:MM"     — без секунд
    Пробелы в начале и в конце пропускаются (некоторые программы шлют ":Sr 05:35:17#").
    Возвращает false, если строка не RA или значения вне диапазона.
*/
bool lx200_parse_ra(const char *s, int32_t *ra_sec);

/*
    Разобрать DEC. Понимает:
      "sDD*MM:SS" / "sDD*MM'SS" — длинный формат ("+22*00:52")
      "sDD*MM"                  — короткий
    Знак необязателен. Разделитель градусов: '*', ':' или байт 0xDF
    (символ градуса в кодировке старых пультов Meade).
    Возвращает false, если строка не DEC или |DEC| > 90°.
*/
bool lx200_parse_dec(const char *s, int32_t *dec_arcsec);

/*
    Записать RA строкой (без '#'): длинный "HH:MM:SS" или короткий "HH:MM.T".
    Значение вне 0..86 399 приводится к суткам (−1 → 23:59:59).
    Возвращает длину строки или 0, если буфер мал.
*/
size_t lx200_format_ra(int32_t ra_sec, bool long_format, char *out, size_t size);

/*
    Записать DEC строкой (без '#'): длинный "sDD*MM:SS" или короткий "sDD*MM".
    Значение больше 90° ограничивается до ±90°.
    Возвращает длину строки или 0, если буфер мал.
*/
size_t lx200_format_dec(int32_t dec_arcsec, bool long_format, char *out, size_t size);

// Буква направления 'n' 's' 'e' 'w' ↔ lx200_dir_t. from_char: false — не направление
bool lx200_dir_from_char(char c, lx200_dir_t *dir);
char lx200_dir_to_char(lx200_dir_t dir);

// Буква скорости 'G' 'C' 'M' 'S' ↔ lx200_rate_t. from_char: false — не скорость
bool lx200_rate_from_char(char c, lx200_rate_t *rate);
char lx200_rate_to_char(lx200_rate_t rate);

/*
    Состояние монтировки — ответ на :GU# в формате OnStepX (урезанный).

    Ответ — буквы-флаги и три цифры в конце, например "nNpEo280":
      'n'   — НЕ ведёт (нет буквы — ведёт);
      'N'   — НЕТ GoTo (нет буквы — идёт GoTo);
      'p'   — не запаркована (парковки пока нет — всегда);
      'E'   — немецкая экваториальная монтировка (всегда);
      'o'   — сторона трубы неизвестна (до этапа 4 плана — всегда);
      цифра 1 — скорость импульсного гидирования (у нас нет — всегда '2', 1×);
      цифра 2 — скорость стрелок, номер OnStepX: :RG# → 2, :RC# → 5, :RM# → 6, :RS# → 8;
      цифра 3 — код ошибки: 0 — нет, 1 — авария мотора (ERR_MOTOR_FAULT у OnStepX).

    Разбор берёт только то, что нам нужно, и не ломается на буквах, которых
    мы не пишем: настоящий OnStepX отвечает длиннее ("nNpEW180" и т. п.).
*/
#define LX200_STATUS_ERR_NONE         0
#define LX200_STATUS_ERR_MOTOR_FAULT  1

typedef struct {
    bool         tracking;      // ведёт
    bool         goto_active;   // идёт GoTo
    lx200_rate_t rate;          // скорость стрелок
    uint8_t      error;         // LX200_STATUS_ERR_*
} lx200_status_t;

// Записать ответ :GU# (без '#'). Возвращает длину или 0, если буфер мал
size_t lx200_format_status(const lx200_status_t *st, char *out, size_t size);

// Разобрать ответ :GU# ('#' в конце можно оставить). false — строка не похожа на ответ
bool lx200_parse_status(const char *s, lx200_status_t *st);

#endif
