#ifndef MOUNT_H
#define MOUNT_H

#include <cstdint>

#include "esp_err.h"

// ============================================================================
//  API МОНТИРОВКИ — команды «на языке монтировки», без строк протокола
// ============================================================================
//
//  Его вызывают парсер LX200, а позже пульт и другие источники (info/lx200.md, раздел 5).
//  Само API моторы не крутит: кладёт команды в очередь motion_task (motion_send),
//  поэтому правило «двигает только одна задача» сохраняется.
//
//  Этап 1: ручное движение и скорости поверх автомата motion_task (info/fsm.md).
//  Дальше: координаты и GoTo.
// ============================================================================

// Направление ручного движения: север/юг — ось DEC, восток/запад — ось RA
enum mount_dir_t {
    MOUNT_DIR_N,
    MOUNT_DIR_S,
    MOUNT_DIR_E,
    MOUNT_DIR_W,
};

// Скорость ручного движения (LX200 :RG# :RC# :RM# :RS#)
enum mount_rate_t {
    MOUNT_RATE_GUIDE,    // правка, гидирование
    MOUNT_RATE_CENTER,   // центрирование
    MOUNT_RATE_FIND,     // поиск
    MOUNT_RATE_SLEW,     // перекладка
};

// Ехать в направлении dir, пока не придёт mount_stop. Не ждёт.
// keepalive = true — источник повторяет команду (пульт по радио): без повтора
// MOTION_KEEPALIVE_MS ось остановится сама
esp_err_t mount_move(mount_dir_t dir, bool keepalive = false);

// Прекратить ручное движение оси направления dir (во время ведения RA вернётся к ведению)
esp_err_t mount_stop(mount_dir_t dir);

// Остановить всё: ручное движение, GoTo и ведение (плавно)
esp_err_t mount_stop_all();

// Ведение за небом (ось RA): true — включить, false — выключить.
// Во время GoTo не меняется: после GoTo ведение включается само.
esp_err_t mount_track(bool on);

// Выбрать скорость ручного движения: GUIDE 0.5×, CENTER 8×, FIND 64×, SLEW максимум.
// Если ось уже едет — переходит на новую скорость сразу.
void mount_set_rate(mount_rate_t rate);

// Состояние монтировки
enum mount_state_t {
    MOUNT_STATE_IDLE,       // стоит, ведения нет
    MOUNT_STATE_TRACKING,   // ведёт за небом
    MOUNT_STATE_GOTO,       // едет к цели
    MOUNT_STATE_FAULT,      // авария драйвера, движение заблокировано
};

mount_state_t mount_get_state();

// Выбранная скорость ручного движения (после включения — SLEW)
mount_rate_t mount_get_rate();

// --- Координаты (модель неба — astro.h) ---
//
// RA — секунды времени 0..86 399, DEC — угловые секунды −324 000..+324 000:
// в тех же единицах их разбирает и пишет lx200_format.

// Куда смотрит телескоп сейчас. До первой синхронизации — полюс мира (домашняя позиция)
void mount_get_radec(int32_t *ra_sec, int32_t *dec_arcsec);

/*
    Синхронизация: «телескоп сейчас смотрит в (ra, dec)». После неё включается ведение.
    ESP_ERR_INVALID_STATE — во время GoTo или аварии (позиция осей не та, что в окуляре).
*/
esp_err_t mount_sync(int32_t ra_sec, int32_t dec_arcsec);

// Была ли синхронизация по звезде (иначе координаты — от домашней позиции)
bool mount_is_synced();

#endif
