#ifndef ASTRO_H
#define ASTRO_H

#include <cstdint>

// ============================================================================
//  МОДЕЛЬ НЕБА: «шаги моторов + время ↔ RA / DEC»
// ============================================================================
//
//  Чистая математика: без FreeRTOS и драйверов, проверяется на компьютере
//  (host_test/test_astro.cpp). Шаги и время ей передаёт mount.cpp.
//
//  Модель от синхронизации: часы, дата и место наблюдения НЕ нужны.
//  При :CM# («телескоп сейчас смотрит на эту звезду») запоминаем точку отсчёта:
//
//      RA₀, DEC₀  — координаты звезды
//      шаги₀      — позиции осей в шагах
//      t₀         — время по часам ESP (мкс от включения)
//
//  Дальше всё считается от неё:
//
//      RA  = RA₀  + звёздное время, прошедшее с t₀  −  поворот оси RA с шаги₀
//      DEC = DEC₀ + поворот оси DEC с шаги₀
//
//  Звёздные часы идут в 1.00273790935 раза быстрее обычных. При ведении ось RA
//  крутится вместе с небом, два слагаемых гасят друг друга — RA не меняется.
//
//  Направления (так задано в mount.cpp, «вперёд» FastAccelStepper):
//    RA  вперёд — на запад, туда же, куда ведение: часовой угол растёт, RA убывает;
//    DEC вперёд — на север: DEC растёт.
//
//  Ограничение первой версии: сторона трубы (pier side) не учитывается.
//  Синхронизация считает, что механический угол DEC равен DEC звезды
//  (труба «на своей» стороне). Переход через полюс считается верно,
//  переворот у меридиана — этап 4 плана.
// ============================================================================

// Во сколько раз звёздные часы быстрее обычных (звёздные сутки = 86 164.0905 с)
#define ASTRO_SIDEREAL_RATIO 1.00273790935

typedef struct {
    // Механика (задаётся один раз в astro_init)
    uint32_t ra_steps_per_rev;    // шагов на оборот оси RA
    uint32_t dec_steps_per_rev;   // шагов на оборот оси DEC

    // Точка отсчёта
    double   ra0_h;               // RA, часы 0..24
    double   dec0_deg;            // механический угол DEC, градусы
    int32_t  ra_steps0;
    int32_t  dec_steps0;
    int64_t  t0_us;

    bool     synced;              // false — точка отсчёта «домашняя», а не по звезде
} astro_model_t;

/*
    Подготовить модель. До первой синхронизации считаем, что монтировка
    в домашней позиции: труба смотрит на полюс (DEC = +90°), RA = 0 ч
    (на полюсе RA не имеет значения). Так прицел Stellarium до синхронизации
    стоит на полюсе мира — там, куда труба и смотрит после выставки.
*/
void astro_init(astro_model_t *m, uint32_t ra_steps_per_rev, uint32_t dec_steps_per_rev,
                int32_t ra_steps, int32_t dec_steps, int64_t t_us);

// Синхронизация: телескоп сейчас смотрит в (ra_h, dec_deg)
void astro_sync(astro_model_t *m, double ra_h, double dec_deg,
                int32_t ra_steps, int32_t dec_steps, int64_t t_us);

// Куда смотрит телескоп при данных позициях осей и времени: RA 0..24 ч, DEC −90..+90°
void astro_get(const astro_model_t *m, int32_t ra_steps, int32_t dec_steps, int64_t t_us,
               double *ra_h, double *dec_deg);

#endif
