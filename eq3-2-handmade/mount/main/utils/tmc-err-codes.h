#ifndef TMC_ERR_CODES_H
#define TMC_ERR_CODES_H

#include "esp_err.h"

// ============================================================================
//  СВОИ КОДЫ ОШИБОК (тип esp_err_t)
// ============================================================================
//
//  esp_err_t — это просто int. Свои коды не должны совпадать с кодами ESP-IDF.
//  ESP-IDF (v6.0.2) занимает: 0 (ESP_OK), -1 (ESP_FAIL), 0x101… (общие) и
//  0x1100…0xFFFF (компоненты: NVS, Wi-Fi, флеш, HTTP, TLS…).
//  Поэтому наш диапазон начинается с 0x20000 — с запасом выше всех кодов ESP-IDF.
//
//  Обычный enum (не enum class): его значения сами превращаются в esp_err_t,
//  поэтому их можно возвращать из функций с типом esp_err_t и сравнивать с ним.
//
//  esp_err_to_name() свои коды не знает (вернёт "UNKNOWN ERROR") —
//  для логов использовать tmc_err_to_name().
// ============================================================================

enum tmc_err_t : esp_err_t {   // «: esp_err_t» — значения хранятся как int и сами превращаются в esp_err_t
    ESP_ERR_TMC_BASE = 0x20000,       // начало диапазона кодов драйвера TMC (сам не используется как ошибка)

    // Номера идут подряд автоматически: BASE + 1, + 2, …
    // Новые коды добавлять ТОЛЬКО В КОНЕЦ — иначе сдвинутся номера всех следующих.
    ESP_ERR_TMC_NO_RESPONSE,          // 0x20001  драйвер не ответил по UART (нет питания VS, адрес, провод)
    ESP_ERR_TMC_WRONG_CHIP,           // 0x20002  ответил не TMC2209 (версия IOIN != 0x21)
    ESP_ERR_TMC_ENN_LOW,              // 0x20003  ENN = 0 до настройки (нет подтяжки EN к 3.3 В)
    ESP_ERR_TMC_WRITE_LOST,           // 0x20004  запись не дошла: счётчик IFCNT не вырос на 1
    ESP_ERR_TMC_RA_NOT_CONFIGURED,    // 0x20005  драйвер RA не настроен (нет связи или ошибка настройки)
    ESP_ERR_TMC_DEC_NOT_CONFIGURED,   // 0x20006  драйвер DEC не настроен (нет связи или ошибка настройки) — RA работает
    ESP_ERR_TMC_INVALID_CRC,
    ESP_ERR_TMC_VERIFY_FAILED
};

// Проверка при сборке: номера не сдвинулись (если упало — код вставили не в конец)
static_assert(ESP_ERR_TMC_DEC_NOT_CONFIGURED == ESP_ERR_TMC_BASE + 6, "номера кодов ошибок TMC сдвинулись");

// Текст кода ошибки: свои коды TMC — сами, остальные — через esp_err_to_name()
const char *tmc_err_to_name(esp_err_t err);

#endif
