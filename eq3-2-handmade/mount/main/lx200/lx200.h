#ifndef LX200_H
#define LX200_H

#include <cstddef>
#include <cstdint>

// ============================================================================
//  ПАРСЕР КОМАНД LX200 (сторона монтировки)
// ============================================================================
//
//  Не привязан к каналу связи: каждый канал (UART, Wi-Fi, ESP-NOW...) заводит свой
//  lx200_ctx_t и отдаёт парсеру байты по одному. Устройство — info/lx200.md.
//
//  Ответы оформляются как у OnStepX (с ним проверены Stellarium, SkySafari, INDI, ASCOM).
//  Тесты на компьютере: host_test/test_lx200.cpp.
//
//  Сейчас: ACK, :Mn# :Ms# :Me# :Mw#, :Qn# :Qs# :Qe# :Qw#, :Q#, :RG# :RC# :RM# :RS#,
//          :Te# :Td# (ведение вкл/выкл — расширение OnStep), :U# (формат координат),
//          :GR# :GD# (где телескоп), :Sr…# :Sd…# (цель), :CM# (синхронизация),
//          :GU# (состояние, формат OnStepX)
// ============================================================================

#define LX200_CMD_MAX_LEN    32     // команда между ':' и '#', длиннее — выбрасывается
#define LX200_REPLY_MAX_LEN  64     // самый длинный ответ с запасом
#define LX200_ACK            0x06   // одиночный байт «какая монтировка?»

// Состояние одного канала связи: у каждого канала своё, чтобы команды не смешивались
typedef struct {
    char        buf[LX200_CMD_MAX_LEN];   // собираемая команда без ':' и '#'
    uint8_t     len;
    bool        collecting;               // после ':' ждём '#'
    int64_t     started_us;               // когда пришёл ':' — сброс зависшего обрывка
    bool        long_format;              // :U# переключает формат координат этого канала
    int32_t     target_ra_sec;            // цель :Sr…# (секунды времени) — для :CM#, позже :MS#
    int32_t     target_dec_arcsec;        // цель :Sd…# (угловые секунды)
    bool        has_target_ra;            // :Sr…# уже приходила
    bool        has_target_dec;           // :Sd…# уже приходила
    bool        keepalive_moves;          // :M?# канала повторяются (пульт ESP-NOW): без повтора — стоп.
                                          // false после lx200_ctx_init, канал ставит сам
    const char *name;                     // имя канала для логов: "uart", "tcp"...
} lx200_ctx_t;

// Подготовить контекст канала (вызвать один раз до первого lx200_feed)
void lx200_ctx_init(lx200_ctx_t *ctx, const char *name);

/*
    Отдать парсеру один принятый байт.
    Если на этом байте собралась команда — выполняет её и кладёт ответ в reply.
    Возвращает длину ответа: 0 — отвечать не нужно (команда ещё не собрана,
    у команды нет ответа или команда неизвестна).
*/
size_t lx200_feed(lx200_ctx_t *ctx, uint8_t byte, char *reply, size_t reply_size);

#endif
